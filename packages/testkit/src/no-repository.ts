/**
 * A graph that works without a repository (manifest `repository: "none"`), the
 * shape of a janitor that inspects the machine: one stage, no job, a validator
 * that accepts what looking at the (empty) workspace shows. The bundle is plain JavaScript written to a scratch directory,
 * and its task names no `repo:`, so a run gets the controller's private
 * repository. The task directory is not inside a git repository.
 */
import { mkdir, symlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { repoRoot } from "./git.js";
import type { TestScope } from "./scope.js";

export const NO_REPOSITORY_GRAPH = "tidy";
export const NO_REPOSITORY_VERSION = "1.0.0";
export const NO_REPOSITORY_REQUEST = "Survey the machine and report what is stale.";

export interface NoRepositoryBundleOptions {
  /** The manifest's `repository` value as written; `undefined` leaves the key out (the default, `required`). Default `"none"`. */
  repository?: string | undefined;
  version?: string;
}

const GRAPH_JS = (version: string) => `// Generated by @graphloom/testkit noRepositoryBundle.
import { observe, stop, validate } from "@graphloom/sdk";

const definition = {
  graphId: ${JSON.stringify(NO_REPOSITORY_GRAPH)},
  version: ${JSON.stringify(version)},
  stages: [{ id: "survey", name: "Survey", requirementIds: ["surveyed"] }],
  requirements: [{ id: "surveyed", statement: "The machine was surveyed.", evidenceSchema: "survey-v1" }],
  defaultValidators: [{ requirementId: "surveyed", validatorId: "surveyed", version: "1" }],
};

export function createGraph() {
  return {
    describe: () => structuredClone(definition),
    advance(view) {
      if (view.receipts.some((r) => r.stageId === "survey" && r.valid)) return stop({ reason: "complete", blocker: "none" }, "surveyed");
      // The only evidence a graph with no job has: what the run's own workspace holds (nothing).
      if (!view.evidence.some((e) => e.kind === "workspace")) return observe({ paths: [], includeWorkspaceManifest: true }, "look at the workspace");
      return validate({ stageId: "survey", requirementIds: ["surveyed"] }, "surveyed");
    },
  };
}

export function validatorById(id) {
  return id === "surveyed"
    ? { evaluate: (input) => (input.evidence.some((e) => e.kind === "workspace") ? { status: "passed", reason: "surveyed" } : { status: "inconclusive", reason: "no survey" }) }
    : undefined;
}
`;

/** The bundle, written under a fresh scratch directory; returns its path. */
export async function noRepositoryBundle(scope: TestScope, options: NoRepositoryBundleOptions = {}): Promise<string> {
  const version = options.version ?? NO_REPOSITORY_VERSION;
  const repository = "repository" in options ? options.repository : "none";
  const manifest = {
    graphId: NO_REPOSITORY_GRAPH,
    version,
    sdkProtocol: 1,
    ...(repository !== undefined ? { repository } : {}),
    entryPoints: { createGraph: "./dist/index.js" },
  };
  const bundle = path.join(await scope.tempDir("gl-tidy-bundle-"), NO_REPOSITORY_GRAPH);
  await mkdir(path.join(bundle, "dist"), { recursive: true });
  await writeFile(path.join(bundle, "graphloom.manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  await writeFile(path.join(bundle, "package.json"), `${JSON.stringify({ name: "graphloom-testkit-tidy", version, private: true, type: "module" }, null, 2)}\n`);
  await writeFile(path.join(bundle, "dist", "index.js"), GRAPH_JS(version));
  await symlink(path.join(repoRoot, "node_modules"), path.join(bundle, "node_modules"));
  return bundle;
}

export interface NoRepositoryFixture {
  dir: string;
  /** The task file's directory: not inside a git repository. */
  taskDir: string;
  taskPath: string;
  /** Run state, which the run's private repository lives in. */
  stateRoot: string;
  /** `<taskDir>/plugins/tidy`, a link to the bundle. */
  bundlePath: string;
  /** The bundle itself, which a test may rewrite to publish an update. */
  bundle: string;
}

export interface NoRepositoryFixtureOptions extends NoRepositoryBundleOptions {
  request?: string;
  /** Extra task lines (`repo: ...`, `base: ...`), written before the request. */
  taskLines?: string;
}

/** A task with no `repo:` and the `none` bundle installed beside it. */
export async function createNoRepositoryFixture(scope: TestScope, options: NoRepositoryFixtureOptions = {}): Promise<NoRepositoryFixture> {
  const dir = await scope.tempDir("gl-tidy-");
  const bundle = await noRepositoryBundle(scope, options);
  const taskDir = path.join(dir, "task");
  await mkdir(path.join(taskDir, "plugins"), { recursive: true });
  const bundlePath = path.join(taskDir, "plugins", NO_REPOSITORY_GRAPH);
  await symlink(bundle, bundlePath);
  const taskPath = path.join(taskDir, "task.yaml");
  await writeFile(taskPath, `graph: ${NO_REPOSITORY_GRAPH}\n${options.taskLines ?? ""}request: ${JSON.stringify(options.request ?? NO_REPOSITORY_REQUEST)}\n`);
  return { dir, taskDir, taskPath, stateRoot: path.join(dir, "state"), bundlePath, bundle };
}
