/**
 * A graph that declares a topology (docs/design-graph-topology.md §12): Build
 * ⇄ Check, a cycle, and a supervisor-only Arbitrate that leaves to either.
 * The bundle is plain JavaScript written to a scratch directory (no build
 * step), imports `@graphloom/sdk` through a `node_modules` link to this
 * checkout's, and ships a rehearsal entry whose scenarios script the agents
 * and the supervisor, so `graphloom check`, `rehearse` and
 * `resume --rehearsal` drive it end to end through the real controller.
 *
 * The happy walk: Build#1 is accepted; the forward move to Check#1 gets
 * `fail`, so the graph reenters Build along the back edge; Build#2 writes
 * its second lap and is accepted again; Check#2 gets `dispute`, so the graph
 * hands over; the supervisor enters Arbitrate, whose ruling settles it; the
 * supervisor leaves along `arbitrate → check`, and Check#3, still disputed
 * but now ruled, is accepted on Arbitrate's receipt. The run completes on the
 * live path build#2 → check#3.
 *
 * The `operator` scenario walks the same way until the arbiter rules
 * `undecidable`: inside Arbitrate's side visit the graph stops, final, for
 * the `ruling` approval it declares (core design §17), and
 * `resume --rehearsal --approve ruling --input ruling=<text>` lifts the stop,
 * Arbitrate validates on the operator's ruling, the supervisor's script
 * continues with its leave to Check, and the run completes as above.
 */
import { mkdir, symlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { repoRoot } from "./git.js";
import type { TestScope } from "./scope.js";
import { createTaskWorkspace, type TaskWorkspace, type TaskWorkspaceOptions } from "./task.js";

export const TOPOLOGY_GRAPH = "topo";
export const TOPOLOGY_VERSION = "1.0.0";
export const TOPOLOGY_REQUEST = "Build the artifact, check it, and settle any dispute.";
/** The file Build writes on each lap. */
export const TOPOLOGY_ARTIFACT = "BUILD.txt";
/** The approval the run waits for inside Arbitrate when the arbiter cannot decide. */
export const TOPOLOGY_APPROVAL = "ruling";
/** The final stop's reason while it waits for TOPOLOGY_APPROVAL. */
export const TOPOLOGY_APPROVAL_STOP = "ruling needs the operator";

const MANIFEST = {
  graphId: TOPOLOGY_GRAPH,
  version: TOPOLOGY_VERSION,
  sdkProtocol: 2,
  entryPoints: { createGraph: "./dist/index.js", rehearsal: "./dist/rehearsal.js" },
};

const GRAPH_JS = `// Generated by @graphloom/testkit topologyBundle.
import { dispatch, reenter, stop, supervise, validate } from "@graphloom/sdk";

const APPROVAL = ${JSON.stringify(TOPOLOGY_APPROVAL)};

const CONTRACTS = { build: "build-v1", check: "check-v1", arbitrate: "ruling-v1" };
const object = (properties, required) => ({ type: "object", properties, required, additionalProperties: false });

const definition = {
  graphId: ${JSON.stringify(TOPOLOGY_GRAPH)},
  version: ${JSON.stringify(TOPOLOGY_VERSION)},
  resultContracts: [
    { name: "build-v1", schema: object({ summary: { type: "string" } }, ["summary"]), evidenceKind: "other" },
    { name: "check-v1", schema: object({ verdict: { type: "string", enum: ["pass", "fail", "dispute"] }, summary: { type: "string" } }, ["verdict", "summary"]), evidenceKind: "review" },
    { name: "ruling-v1", schema: object({ ruling: { type: "string" }, summary: { type: "string" } }, ["ruling", "summary"]), evidenceKind: "review" },
  ],
  stages: [
    { id: "build", name: "Build", requirementIds: ["built"] },
    { id: "check", name: "Check", requirementIds: ["checked"] },
    { id: "arbitrate", name: "Arbitrate", requirementIds: ["ruled"], entry: "supervisor", maxVisits: 2 },
  ],
  edges: [
    { from: "build", to: "check" },
    { from: "check", to: "build" },
    { from: "arbitrate", to: "build" },
    { from: "arbitrate", to: "check" },
  ],
  start: "build",
  terminal: ["check"],
  approvals: [
    { id: ${JSON.stringify(TOPOLOGY_APPROVAL)}, stageId: "arbitrate", description: "Rule on a dispute the arbiter could not decide", inputs: [{ name: "ruling", description: "The ruling, in a sentence" }] },
  ],
  requirements: [
    { id: "built", statement: "The builder reports a build of the current workspace.", evidenceSchema: "build-v1" },
    { id: "checked", statement: "The checker passes the build, or a ruling settles its dispute.", evidenceSchema: "check-v1", prerequisiteRequirementIds: ["ruled"] },
    { id: "ruled", statement: "An arbiter rules on the disputed check.", evidenceSchema: "ruling-v1" },
  ],
  defaultValidators: [
    { requirementId: "built", validatorId: "built", version: "1" },
    { requirementId: "checked", validatorId: "checked", version: "1" },
    { requirementId: "ruled", validatorId: "ruled", version: "1" },
  ],
};

const JOBS = {
  build: { kind: "agent", purpose: "work", writeScope: [${JSON.stringify(TOPOLOGY_ARTIFACT)}], instruction: "Write ${TOPOLOGY_ARTIFACT}. Reply with a summary." },
  check: { kind: "agent", purpose: "review", readOnly: true, instruction: "Check ${TOPOLOGY_ARTIFACT}. Reply with a verdict (pass, fail or dispute) and a summary." },
  arbitrate: { kind: "agent", purpose: "review", readOnly: true, instruction: "Rule on the disputed check. Reply with a ruling and a summary." },
};

/** The node's newest contract-valid result produced under \`attempt\` (a work result keeps its agent wrapper; a review result is the output itself). */
function result(evidence, node, attempt) {
  for (let i = evidence.length - 1; i >= 0; i--) {
    const e = evidence[i];
    const producer = e.payload?.producer;
    if (e.resultSchema !== CONTRACTS[node] || e.contract?.status === "invalid") continue;
    if (producer?.stageId === node && (attempt === undefined || producer.attempt === attempt)) return e.payload.codingAgent?.output ?? e.payload;
  }
  return undefined;
}

/** The operator's newest decision on the ruling approval, from the run's evidence. */
function operatorRuling(records) {
  for (let i = records.length - 1; i >= 0; i--) {
    const p = records[i].payload;
    if (p?.type === "operator-approval" && p.approvalId === APPROVAL) return p;
  }
  return undefined;
}

const accepted = (view, node) => view.receipts.some((r) => r.stageId === node && r.valid) && view.openAttempt?.[node] !== true;
const ruled = (receipts) => (receipts ?? []).some((r) => r.stageId === "arbitrate" && r.valid);
const work = (node) => dispatch({ stageId: node, resultSchema: CONTRACTS[node], ...JOBS[node] }, \`work \${node}\`);

export function advance(view) {
  const topology = view.topology;
  const side = topology.sideVisit;
  if (side !== undefined) {
    // Inside the supervisor's side visit: do the node's work; only the supervisor leaves.
    const done = result(view.evidence, side.stageId, side.attempt);
    if (done === undefined) return work(side.stageId);
    if (done.ruling === "undecidable" && operatorRuling(view.evidence) === undefined) {
      // A final stop that waits for the declared approval: how a node waits for the operator.
      const blocker = \`The arbiter could not decide: \${done.summary}\\nRule on it: graphloom resume \${view.runId} --approve \${APPROVAL} --input ruling="…"\`;
      return stop({ reason: ${JSON.stringify(TOPOLOGY_APPROVAL_STOP)}, blocker, retryable: false }, "wait for the operator's ruling");
    }
    return validate({ stageId: side.stageId }, \`validate \${side.stageId}\`);
  }
  const tail = topology.path[topology.path.length - 1];
  if (tail.stageId === "build") {
    if (accepted(view, "build")) return work("check");
    if (result(view.evidence, "build", tail.attempt) === undefined) return work("build");
    return validate({ stageId: "build" }, "validate build");
  }
  const checked = result(view.evidence, "check", tail.attempt);
  if (checked === undefined) return work("check");
  if (accepted(view, "check")) return stop({ reason: "complete", blocker: "none" }, "the live path is accepted");
  if (checked.verdict === "fail") return reenter({ stageId: "build", reason: \`check failed: \${checked.summary}\` }, "back to build");
  if (checked.verdict === "dispute" && !ruled(view.receipts)) return supervise({ reason: \`check disputed: \${checked.summary}\` }, "a dispute only a ruling settles");
  return validate({ stageId: "check" }, "validate check");
}

const VALIDATORS = {
  built: {
    evaluate(input) {
      const built = result(input.evidence, "build");
      return built !== undefined ? { status: "passed", reason: \`built: \${built.summary}\` } : { status: "inconclusive", reason: "no build result" };
    },
  },
  checked: {
    evaluate(input) {
      const checked = result(input.evidence, "check");
      if (checked === undefined) return { status: "inconclusive", reason: "no check result" };
      if (checked.verdict === "pass") return { status: "passed", reason: "the check passed" };
      if (checked.verdict === "fail") return { status: "failed", reason: \`the check failed: \${checked.summary}\` };
      return ruled(input.receipts)
        ? { status: "passed", reason: "the dispute is settled by a ruling" }
        : { status: "inconclusive", reason: "disputed, and no ruling yet" };
    },
  },
  ruled: {
    evaluate(input) {
      const ruling = result(input.evidence, "arbitrate");
      if (ruling === undefined) return { status: "inconclusive", reason: "no ruling" };
      if (ruling.ruling !== "undecidable") return { status: "passed", reason: \`ruled: \${ruling.ruling}\` };
      const operator = operatorRuling([...(input.history ?? []), ...input.evidence]);
      if (operator === undefined) return { status: "inconclusive", reason: "undecidable, and the operator has not ruled" };
      return { status: "passed", reason: operator.decision === "approve" ? \`ruled by the operator: \${operator.inputs?.ruling ?? ""}\` : "the operator declined to rule" };
    },
  },
};

export function validatorById(id) {
  return VALIDATORS[id];
}

export function createGraph() {
  return { describe: () => structuredClone(definition), advance };
}
`;

const SUPERVISOR = {
  enter: { action: { type: "enter", enter: { stageId: "arbitrate", reason: "the check is disputed; an arbiter rules" } }, reason: "enter arbitrate" },
  back: { action: { type: "return", return: { summary: "back to the graph" } }, reason: "return" },
  leave: { action: { type: "reenter", reenter: { stageId: "check", reason: "the ruling settles the dispute; check again" } }, reason: "leave arbitrate to check" },
};

const REHEARSAL_JS = `// Generated by @graphloom/testkit topologyBundle.
const build = (lap) => ({ output: { summary: \`lap \${lap}\` }, effects: [{ path: ${JSON.stringify(TOPOLOGY_ARTIFACT)}, bytes: \`lap \${lap}\\n\` }] });
const check = (verdict) => ({ output: { verdict, summary: \`the build is a \${verdict}\` } });
const supervisor = ${JSON.stringify([SUPERVISOR.enter, SUPERVISOR.back, SUPERVISOR.leave, SUPERVISOR.back])};

export const rehearsal = {
  scenarios: {
    happy: {
      results: {
        "build-v1": [build(1), build(2)],
        "check-v1": [check("fail"), check("dispute")],
        "ruling-v1": [{ output: { ruling: "the dispute is unfounded", summary: "the build stands" } }],
      },
      supervisor,
      expect: {
        status: "succeeded",
        receipts: ["build", "check", "arbitrate"],
        path: ["build", "check"],
        recovery: ["supervise", "supervisor_node_settled"],
      },
    },
    operator: {
      results: {
        "build-v1": [build(1), build(2)],
        "check-v1": [check("fail"), check("dispute")],
        "ruling-v1": [{ output: { ruling: "undecidable", summary: "the check and the build each have a case" } }],
      },
      // The same script: the leave and the last return answer after the operator's approval.
      supervisor,
      expect: {
        status: "stopped",
        stopReason: ${JSON.stringify(TOPOLOGY_APPROVAL_STOP)},
        receipts: ["build"],
        path: ["build", "check"],
        recovery: ["supervise"],
      },
    },
  },
};
`;

/** The topology bundle, written under a fresh scratch directory; returns its path. */
export async function topologyBundle(scope: TestScope): Promise<string> {
  const bundle = path.join(await scope.tempDir("gl-topo-bundle-"), TOPOLOGY_GRAPH);
  await mkdir(path.join(bundle, "dist"), { recursive: true });
  await writeFile(path.join(bundle, "graphloom.manifest.json"), `${JSON.stringify(MANIFEST, null, 2)}\n`);
  await writeFile(path.join(bundle, "package.json"), `${JSON.stringify({ name: "graphloom-testkit-topo", version: TOPOLOGY_VERSION, private: true, type: "module" }, null, 2)}\n`);
  await writeFile(path.join(bundle, "dist", "index.js"), GRAPH_JS);
  await writeFile(path.join(bundle, "dist", "rehearsal.js"), REHEARSAL_JS);
  await symlink(path.join(repoRoot, "node_modules"), path.join(bundle, "node_modules"));
  return bundle;
}

/** A repository and a task naming the topology graph, its bundle installed beside the task. */
export async function createTopologyFixture(
  scope: TestScope,
  options: Omit<TaskWorkspaceOptions, "graph" | "request" | "bundle"> & { request?: string } = {},
): Promise<TaskWorkspace> {
  const bundle = await topologyBundle(scope);
  return createTaskWorkspace(scope, { ...options, graph: TOPOLOGY_GRAPH, request: options.request ?? TOPOLOGY_REQUEST, bundle });
}
