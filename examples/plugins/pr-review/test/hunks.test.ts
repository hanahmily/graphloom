import { describe, expect, it } from "vitest";
import {
  formatHunkFile,
  globToRegExp,
  hasGeneratedHeader,
  hunksFromUnifiedDiff,
  isTestPath,
  matchesGeneratedGlob,
  parseHunkFile,
  unquoteGitPath,
} from "../src/metrics/index.js";

describe("hunks", () => {
  it("round-trips the hunk file and rejects bad lines", () => {
    const h = parseHunkFile("# note\na/b.go:3-5\na/b.go:9\n\n");
    expect(h.get("a/b.go")).toEqual([
      { start: 3, end: 5 },
      { start: 9, end: 9 },
    ]);
    expect(formatHunkFile(h)).toBe("a/b.go:3-5\na/b.go:9-9\n");
    expect(() => parseHunkFile("nope")).toThrow(/want path:start-end/);
    expect(() => parseHunkFile("a.go:5-3")).toThrow(/bad range/);
  });

  it("takes head-side ranges from a -U0 diff and ignores deletions", () => {
    const diff = [
      "diff --git a/x.go b/x.go",
      "--- a/x.go",
      "+++ b/x.go",
      "@@ -3,2 +3,0 @@",
      "@@ -10 +8 @@",
      "@@ -20,0 +18,4 @@",
      "diff --git a/y.go b/y.go",
      "--- a/y.go",
      "+++ /dev/null",
      "@@ -1,2 +0,0 @@",
      "",
    ].join("\n");
    expect([...hunksFromUnifiedDiff(diff)]).toEqual([
      [
        "x.go",
        [
          { start: 8, end: 8 },
          { start: 18, end: 21 },
        ],
      ],
    ]);
  });
});

describe("git path quoting", () => {
  it("decodes quoted non-ASCII and escaped names in diff headers", () => {
    expect(unquoteGitPath('"caf\\303\\251.go"')).toBe("café.go");
    expect(unquoteGitPath('"b/a\\"b\\\\c\\td.ts"')).toBe('b/a"b\\c\td.ts');
    expect(unquoteGitPath("b/plain.go")).toBe("b/plain.go");
    const diff = '--- a/x\n+++ "b/caf\\303\\251.go"\n@@ -1 +1,2 @@\n';
    expect([...hunksFromUnifiedDiff(diff).keys()]).toEqual(["café.go"]);
  });
});

describe("generated and test paths", () => {
  it("matches globs", () => {
    expect(globToRegExp("**/*.pb.go").test("a/b/x.pb.go")).toBe(true);
    expect(globToRegExp("*.pb.go").test("a/x.pb.go")).toBe(false);
    expect(matchesGeneratedGlob(["*.pb.go"], "a/x.pb.go")).toBe(true);
    expect(matchesGeneratedGlob(["gen/*.ts"], "src/gen/x.ts")).toBe(false);
  });
  it("detects generated headers", () => {
    expect(hasGeneratedHeader("go", "// Code generated by x. DO NOT EDIT.\n\npackage p\n")).toBe(true);
    expect(hasGeneratedHeader("go", "package p\n// Code generated by x. DO NOT EDIT.\n")).toBe(false);
    expect(hasGeneratedHeader("typescript", "/* @generated */\nexport {};\n")).toBe(true);
    expect(hasGeneratedHeader("typescript", "export {};\n")).toBe(false);
  });
  it("recognises test files", () => {
    for (const p of ["a/b_test.go", "src/x.test.ts", "src/x.spec.tsx", "pkg/test/helper.ts", "a/__tests__/b.ts"]) {
      expect(isTestPath(p), p).toBe(true);
    }
    for (const p of ["a/b.go", "src/x.ts", "src/contest.ts"]) expect(isTestPath(p), p).toBe(false);
  });
});
